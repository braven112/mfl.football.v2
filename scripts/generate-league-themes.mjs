#!/usr/bin/env node
/**
 * Compile the theme library (src/themes/<id>.json) into
 * src/styles/league-themes.generated.css — one light and one dark block per
 * theme, applied to every <html data-league> that uses it.
 *
 *   node scripts/generate-league-themes.mjs          # write the CSS
 *   node scripts/generate-league-themes.mjs --check  # exit 1 if it is stale
 *
 * Which surfaces wear which theme comes from the league registry (`theme` on
 * each entry, keyed by its `navSlug`, the value the layouts put on
 * data-league) plus THEMED_SURFACES below for the one surface that is not a
 * registry league. The registry is read with DEMO_PROFILE set so demo-only
 * slots (the keeper league) get their selectors too — the CSS is shared by
 * every deployment, and a slot missing here renders the default theme there.
 *
 * Every block is COMPLETE over THEMED_TOKENS (src/config/theme-tokens.mjs),
 * and each light block is overridden token-for-token by its dark block in
 * dark mode, so no theme can leak another's value through the cascade.
 * Specificity: light html[data-league] is 0,1,1 (beats :root), dark
 * html.dark[data-league] is 0,2,1 (beats html.dark and the light block).
 *
 * Plan: docs/plans/league-themes.md. Guard: tests/league-themes.test.ts.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const THEMES_DIR = path.join(ROOT, 'src/themes');
export const OUTPUT = path.join(ROOT, 'src/styles/league-themes.generated.css');

/**
 * data-league values that are not registry leagues, and their theme.
 * `mfl` is the shared-host MFL Live app — MflAppLayout.astro sets the
 * attribute directly; it must never be added to the registry.
 */
export const THEMED_SURFACES = { mfl: 'mfl-live' };

/** The theme for an <html> that names no league (Storybook, bare layouts). */
export const DEFAULT_THEME_ID = 'theleague';

export function loadThemes(dir = THEMES_DIR) {
  const themes = {};
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
    const theme = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
    if (theme.id !== path.basename(file, '.json')) {
      throw new Error(`${file}: id "${theme.id}" must match its filename`);
    }
    themes[theme.id] = theme;
  }
  return themes;
}

/** navSlug → theme id, across the registry and THEMED_SURFACES. */
export async function loadSurfaces() {
  process.env.DEMO_PROFILE ||= '1';
  const { ALL_LEAGUES } = await import('../src/config/leagues-data.mjs');
  const surfaces = {};
  for (const league of ALL_LEAGUES) {
    if (!league.theme) throw new Error(`league "${league.slug}" has no theme`);
    surfaces[league.navSlug] = league.theme;
  }
  return { ...surfaces, ...THEMED_SURFACES };
}

const comment = (text) => `/* ${text.replace(/\*\//g, '* /')} */`;

function block(selectors, values, tokens, notes) {
  const lines = [];
  for (const token of tokens) {
    const value = values[token];
    if (value == null) continue;
    const note = notes?.[token];
    lines.push(`  ${token}: ${value};${note ? ` ${comment(note)}` : ''}`);
  }
  return `${selectors.join(',\n')} {\n${lines.join('\n')}\n}\n`;
}

export function buildThemeCss(themes, surfaces, tokens) {
  const byTheme = {};
  for (const [slug, id] of Object.entries(surfaces)) {
    if (!themes[id]) throw new Error(`surface "${slug}" names unknown theme "${id}"`);
    (byTheme[id] ??= []).push(slug);
  }
  let css =
    '/* GENERATED by scripts/generate-league-themes.mjs from src/themes/*.json — do not edit.\n' +
    '   Edit the theme file and re-run the script. */\n';
  for (const id of Object.keys(byTheme).sort()) {
    const theme = themes[id];
    const slugs = byTheme[id].sort();
    const light = slugs.map((s) => `html[data-league="${s}"]`);
    const dark = slugs.map((s) => `html.dark[data-league="${s}"]`);
    if (id === DEFAULT_THEME_ID) {
      light.push('html:not([data-league])');
      dark.push('html.dark:not([data-league])');
    }
    css += `\n${comment(`${theme.name} (${id}) — ${theme.description}`)}\n`;
    css += block(light, theme.light, tokens, theme.notes);
    css += block(dark, theme.dark, tokens);
  }
  return css;
}

async function main() {
  const { THEMED_TOKENS } = await import('../src/config/theme-tokens.mjs');
  const css = buildThemeCss(loadThemes(), await loadSurfaces(), THEMED_TOKENS);
  let current = '';
  try {
    current = fs.readFileSync(OUTPUT, 'utf8');
  } catch (err) {
    if (/** @type {NodeJS.ErrnoException} */ (err).code !== 'ENOENT') throw err;
  }
  if (process.argv.includes('--check')) {
    if (current !== css) {
      console.error(`${path.relative(ROOT, OUTPUT)} is stale — run node scripts/generate-league-themes.mjs`);
      process.exit(1);
    }
    return;
  }
  if (current !== css) fs.writeFileSync(OUTPUT, css);
  console.log(`${current === css ? 'unchanged' : 'wrote'} ${path.relative(ROOT, OUTPUT)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
