#!/usr/bin/env node
/**
 * Write a league's MFL settings digest — its rules as configured on MFL, in
 * plain words — to data/<slug>/derived/rules-from-mfl.md. Ask Roger falls back
 * to it where the league's written rulebook is silent or missing, and a league
 * with no written rulebook shows it on its Rules page
 * (src/utils/mfl-settings-digest.mjs, src/utils/league-rulebook.ts).
 *
 *   node scripts/compute-mfl-settings-digest.mjs --league=<slug>
 *
 * Reads the newest data/<slug>/mfl-feeds/<year>/ that has a league.json (and
 * its rules.json when present). Writes only when the text changed, so a sync
 * where no setting moved commits nothing. A league with no feeds yet is a
 * no-op, not an error.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getLeagueBySlug } from '../src/config/leagues-data.mjs';
import { mflSettingsDigest } from '../src/utils/mfl-settings-digest.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const slug = process.argv.find((a) => a.startsWith('--league='))?.split('=')[1];
const league = slug && getLeagueBySlug(slug);
if (!league) {
  console.error(`[mfl-settings-digest] unknown league "${slug}" (pass --league=<slug>)`);
  process.exit(1);
}

const feedsDir = path.join(ROOT, league.dataPath, 'mfl-feeds');
const year = existsSync(feedsDir)
  ? readdirSync(feedsDir)
      .filter((d) => /^\d{4}$/.test(d) && existsSync(path.join(feedsDir, d, 'league.json')))
      .sort()
      .pop()
  : undefined;
if (!year) {
  console.log(`[mfl-settings-digest] ${league.slug}: no league.json yet — skipped`);
  process.exit(0);
}

const read = (file) => {
  try {
    return JSON.parse(readFileSync(path.join(feedsDir, year, file), 'utf8'));
  } catch {
    return null; // rules.json arrives with the first sync after it was added
  }
};
const codes = JSON.parse(readFileSync(path.join(ROOT, 'src/data/mfl-scoring-codes.json'), 'utf8'));
const digest = mflSettingsDigest(read('league.json'), read('rules.json'), codes);
const text = `<!-- Generated by scripts/compute-mfl-settings-digest.mjs from the ${year} MFL feeds. Do not edit: change the league on MFL. -->\n${digest}\n`;

const out = path.join(ROOT, league.dataPath, 'derived', 'rules-from-mfl.md');
// Read-then-compare, no exists() check first: a missing file simply reads as
// "different" (no check-then-use window between a stat and the write).
let current = null;
try {
  current = readFileSync(out, 'utf8');
} catch {
  // not written yet
}
if (current === text) {
  console.log(`[mfl-settings-digest] ${league.slug}: unchanged`);
} else {
  mkdirSync(path.dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`[mfl-settings-digest] ${league.slug}: wrote ${path.relative(ROOT, out)} (${year})`);
}
