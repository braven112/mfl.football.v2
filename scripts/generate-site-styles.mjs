#!/usr/bin/env node
/**
 * Compile the site-style library (src/styles/site-styles/<id>.json) into
 * src/styles/site-styles.generated.css — one block per style, applied to every
 * <html data-site-theme> that wears it. The layout sets that attribute for the
 * whole page from the league's registry `siteTheme` (or a `?theme=` preview),
 * so a style reaches every page and every component at once.
 *
 *   node scripts/generate-site-styles.mjs          # write the CSS
 *   node scripts/generate-site-styles.mjs --check  # exit 1 if it is stale
 *
 * A token a style leaves null is emitted as nothing, so the consumer's own
 * fallback (`var(--style-x, <own value>)`) renders. Editorial also covers an
 * <html> with no attribute (the non-league layouts, Storybook's default).
 * Specificity: html[data-site-theme] is 0,1,1 and html.dark[data-site-theme]
 * 0,2,1 — style tokens never collide with the league theme's tokens, so the
 * two blocks do not compete.
 *
 * Plan: docs/plans/site-styles.md. Guard: tests/site-styles.test.ts.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const STYLES_DIR = path.join(ROOT, 'src/styles/site-styles');
export const OUTPUT = path.join(ROOT, 'src/styles/site-styles.generated.css');

/** The style for an <html> that names none. */
export const DEFAULT_STYLE_ID = 'editorial';

/**
 * @typedef {{ id: string, name: string, description: string,
 *   tokens: Record<string, string | null>, dark?: Record<string, string> }} SiteStyle
 * @returns {Record<string, SiteStyle>}
 */
export function loadStyles(dir = STYLES_DIR) {
  /** @type {Record<string, SiteStyle>} */
  const styles = {};
  for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
    const style = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
    if (style.id !== path.basename(file, '.json')) {
      throw new Error(`${file}: id "${style.id}" must match its filename`);
    }
    styles[style.id] = style;
  }
  return styles;
}

const comment = (text) => `/* ${text.replace(/\*\//g, '* /')} */`;

function block(selectors, values, tokens) {
  const lines = tokens.filter((t) => values?.[t] != null).map((t) => `  ${t}: ${values[t]};`);
  if (!lines.length) return '';
  return `${selectors.join(',\n')} {\n${lines.join('\n')}\n}\n`;
}

export function buildStyleCss(styles, tokens) {
  let css =
    '/* GENERATED by scripts/generate-site-styles.mjs from src/styles/site-styles/*.json — do not edit.\n' +
    '   Edit the style file and re-run the script. */\n';
  for (const id of Object.keys(styles).sort()) {
    const style = styles[id];
    const base = [`html[data-site-theme="${id}"]`];
    const dark = [`html.dark[data-site-theme="${id}"]`];
    if (id === DEFAULT_STYLE_ID) {
      base.push('html:not([data-site-theme])');
      dark.push('html.dark:not([data-site-theme])');
    }
    const body = block(base, style.tokens, tokens) + block(dark, style.dark, tokens);
    css += `\n${comment(`${style.name} (${id}) — ${style.description}`)}\n`;
    css += body || `${comment('Every token is the components’ own value.')}\n`;
  }
  return css;
}

async function main() {
  const { STYLE_TOKENS } = await import('../src/config/style-tokens.mjs');
  const css = buildStyleCss(loadStyles(), STYLE_TOKENS);
  let current = '';
  try {
    current = fs.readFileSync(OUTPUT, 'utf8');
  } catch (err) {
    if (/** @type {NodeJS.ErrnoException} */ (err).code !== 'ENOENT') throw err;
  }
  if (process.argv.includes('--check')) {
    if (current !== css) {
      console.error(`${path.relative(ROOT, OUTPUT)} is stale — run node scripts/generate-site-styles.mjs`);
      process.exit(1);
    }
    return;
  }
  if (current !== css) fs.writeFileSync(OUTPUT, css);
  console.log(`${current === css ? 'unchanged' : 'wrote'} ${path.relative(ROOT, OUTPUT)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
